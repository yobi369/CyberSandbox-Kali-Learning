#!/bin/sh
set -eu

: "${MIGRATOR_DATABASE_URL:?MIGRATOR_DATABASE_URL must be provided by the private staging database}"
: "${CYBERSANDBOX_APP_PASSWORD:?CYBERSANDBOX_APP_PASSWORD must be generated by Render}"

# Build the restricted runtime connection string without printing credentials.
DATABASE_URL="$(node --input-type=module -e '
  const url = new URL(process.env.MIGRATOR_DATABASE_URL);
  url.username = "cybersandbox_app";
  url.password = process.env.CYBERSANDBOX_APP_PASSWORD;
  process.stdout.write(url.toString());
')"

export DATABASE_URL
# The API process must never inherit migration-owner credentials or the role password.
unset MIGRATOR_DATABASE_URL CYBERSANDBOX_APP_PASSWORD

exec node dist-server/server/index.js
